export function imageDescription(src: string | undefined, fallback: string) {
  if (!src) return fallback;
  const key = src.split("?")[0].replace(/^https:\/\/www\.setlesstudio\.com\//, "/");
  return descriptions[key] ?? fallback;
}


export function coverSizes(src: string, sizes: string) {
  if (!/^https:\/\/(?:images\.pexels\.com|(?:images|plus)\.unsplash\.com)\//.test(src)) return {};
  const url = new URL(src);
  const srcSet = [384, 640, 960, 1280].map(width => {
    url.searchParams.set("w", String(width));
    return `${url.href} ${width}w`;
  }).join(", ");
  return { srcSet, sizes };
}
